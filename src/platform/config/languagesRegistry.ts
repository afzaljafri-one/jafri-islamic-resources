  id: string; // ISO 639-1 / BCP-47 (e.g. 'en', 'es', 'ar', 'hi', 'bn')
  bcp47: string;
  name: string;
  nativeName: string;
  scriptCode: string; // ISO 15924 (e.g. 'Latn', 'Arab', 'Deva', 'Beng', 'Guru', 'Taml')
